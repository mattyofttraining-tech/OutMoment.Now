/** Localized copy of a quest; unknown titles (AI quests) pass through as-is. */
export function localizeQuest<T extends Pick<Quest, 'title' | 'prompt'>>(
  quest: T,
  locale: LocaleCode,
): T {
  const entry = QUEST_I18N[locale]?.[quest.title];
  if (!entry) return quest;
  return { ...quest, title: entry[0], prompt: entry[1] };
}

/** Localize a bare quest title (photo captions reuse quest titles). */
export function localizeQuestTitle(title: string, locale: LocaleCode): string {
  return QUEST_I18N[locale]?.[title]?.[0] ?? title;
}
